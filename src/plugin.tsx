import { ChangeEvent, FormEvent, MouseEvent, useRef, useState, useEffect } from "react";
import { createRoot } from "react-dom/client";
import {
  Reshaped,
  View,
  Button,
  Modal,
  Text,
  useToggle,
  useTheme,
  useIsomorphicLayoutEffect,
  TextField,
  FormControl,
  useToast,
  Divider,
} from "reshaped";
import * as ThemeService from "services/theme/index.js";
import type * as G from "types/global.js";
import { subscribeToCanvas, receiveCanvasMessage } from "utilities/channel.js";
import "reshaped/themes/figma/theme.css";

export default function copyToClipboard(value: string) {
  try {
    // @ts-expect-error -- window.copy is not typed
    if (window.copy) {
      // @ts-expect-error -- window.copy is not typed
      window.copy(value);
    } else {
      const area = document.createElement("textarea");
      document.body.appendChild(area);
      area.value = value;
      area.focus();
      area.select();
      const result = document.execCommand("copy");
      document.body.removeChild(area);
      if (!result) {
        throw new Error();
      }
    }
  } catch (e) {
    console.error(`Unable to copy the value: ${value}`);
    return false;
  }
  return true;
}

const App = () => {
  const { setColorMode } = useTheme();
  const toast = useToast();
  const confirmToggle = useToggle();
  const [themeJson, setThemeJson] = useState<string | null>(null);
  const [themeName, setThemeName] = useState("");
  const theme = themeJson ? (JSON.parse(themeJson) as G.Theme) : null;
  const titleFontFallback = theme?.fontFamily.title.family.split(", ")[0];
  const bodyFontFallback = theme?.fontFamily.body.family.split(", ")[0];
  const [titleFontFamily, setTitleFontFamily] = useState("");
  const [bodyFontFamily, setBodyFontFamily] = useState("");
  const inputRef = useRef<HTMLInputElement | null>(null);
  const [extractModeName, setExtractModeName] = useState("");
  const [extractedThemeJson, setExtractedThemeJson] = useState<string | null>(null);
  const [isExtracting, setIsExtracting] = useState(false);

  const handleThemeUploadConfirm = () => {
    if (!themeJson) return;
    ThemeService.plugin.requestUploadTheme({
      theme: JSON.parse(themeJson),
      name: themeName,
      fontFamily: { title: titleFontFamily || titleFontFallback!, body: bodyFontFamily || bodyFontFallback! },
    });
    confirmToggle.deactivate();
    setThemeJson(null);
  };

  const handleUploadClick = (e: FormEvent | MouseEvent) => {
    e.preventDefault();

    if (!themeName) {
      toast.show({ text: "We're missing the theme name 😬" });
      return;
    }

    setThemeJson(null);
    inputRef.current!.value = "";
    inputRef.current!.click();
  };

  const handleThemeUpload = (e: ChangeEvent<HTMLInputElement>) => {
    const files = e.target.files;
    if (!files || files.length <= 0) return;

    const file = files[0];
    const reader = new FileReader();

    reader.onload = (e) => {
      try {
        const res = e.target?.result;

        if (!(typeof res === "string")) return;

        setThemeJson(res);
        confirmToggle.activate();
      } catch (error) {
        console.error("Error reading or parsing JSON file", error);
      }
    };

    reader.readAsText(file);
  };

  const handleCancel = () => {
    confirmToggle.deactivate();
  };

  const handleExtractTheme = (e: FormEvent | MouseEvent) => {
    e.preventDefault();

    if (!extractModeName) {
      toast.show({ text: "Please enter a theme name 😬" });
      return;
    }

    setIsExtracting(true);
    setExtractedThemeJson(null);
    ThemeService.plugin.requestExtractTheme({ modeName: extractModeName });
  };

  const handleCopyJson = () => {
    if (!extractedThemeJson) return;

    copyToClipboard(extractedThemeJson);
    toast.show({ text: "JSON copied to clipboard! 📋" });
  };

  useEffect(() => {
    const subscription = subscribeToCanvas((msg) => {
      receiveCanvasMessage(msg, ThemeService.CanvasActionType.themeExtracted, (payload) => {
        setIsExtracting(false);
        if ("error" in payload) {
          toast.show({ text: `Error: ${payload.error}` });
          setExtractedThemeJson(null);
        } else {
          const jsonString = JSON.stringify(payload.theme, null, 2);
          setExtractedThemeJson(jsonString);
          toast.show({ text: "Theme extracted successfully! ✨" });
        }
      });
    });

    return () => {
      subscription.unsubscribe();
    };
  }, [toast]);

  useIsomorphicLayoutEffect(() => {
    if (!document.documentElement.classList.contains("figma-dark")) return;
    setColorMode("dark");
  }, [setColorMode]);

  return (
    <>
      <View padding={4} gap={4} divided>
        <View.Item>
          <Text variant="body-2" weight="medium">
            Sync theme from code
          </Text>
          <Text color="neutral-faded" variant="body-3">
            Select a `theme.json` filed generated by Reshaped in your code repository.
          </Text>
        </View.Item>
        <View.Item>
          <form onSubmit={handleUploadClick}>
            <FormControl>
              <FormControl.Label>Theme name</FormControl.Label>
              <View gap={2} direction="row">
                <View.Item grow>
                  <TextField
                    name="themeName"
                    placeholder="Reshaped"
                    onChange={(args) => setThemeName(args.value)}
                    value={themeName}
                    variant="faded"
                  />
                </View.Item>
                <Button color="primary" onClick={handleUploadClick}>
                  Upload
                </Button>
                <input type="file" accept=".json" onChange={handleThemeUpload} hidden ref={inputRef} />
              </View>
              <FormControl.Helper>Theme name will be used as a Figma variables mode</FormControl.Helper>
            </FormControl>
          </form>
        </View.Item>
      </View>
      <View padding={4} gap={4} divided>
        <View.Item>
          <Text variant="body-2" weight="medium">
            Extract theme from Figma
          </Text>
          <Text color="neutral-faded" variant="body-3">
            Extract theme variables and styles from a Figma mode and convert them to JSON.
          </Text>
        </View.Item>
        <View.Item>
          <form onSubmit={handleExtractTheme}>
            <FormControl>
              <FormControl.Label>Theme name</FormControl.Label>
              <View gap={2} direction="row">
                <View.Item grow>
                  <TextField
                    name="extractModeName"
                    placeholder="Light"
                    onChange={(args) => setExtractModeName(args.value)}
                    value={extractModeName}
                    variant="faded"
                  />
                </View.Item>
                <Button color="primary" onClick={handleExtractTheme} loading={isExtracting}>
                  Extract
                </Button>
              </View>
              <FormControl.Helper>Enter the name of the Figma variable mode to extract theme from</FormControl.Helper>
            </FormControl>
          </form>
        </View.Item>
        {extractedThemeJson && (
          <View.Item>
            <View gap={2}>
              <View direction="row" align="center" justify="space-between">
                <Text variant="body-2" weight="medium">
                  Extracted Theme JSON
                </Text>
                <Button size="small" onClick={handleCopyJson}>
                  Copy
                </Button>
              </View>
              <View
                padding={3}
                backgroundColor="neutral-faded"
                borderRadius="medium"
                maxHeight="300px"
                overflow="auto"
                attributes={{
                  style: {
                    whiteSpace: "pre-wrap",
                    wordBreak: "break-all",
                  },
                }}
              >
                <Text variant="caption-1" monospace>
                  {extractedThemeJson}
                </Text>
              </View>
            </View>
          </View.Item>
        )}
      </View>
      <Modal active={confirmToggle.active} onClose={confirmToggle.deactivate}>
        <View gap={3}>
          <View.Item>
            <Modal.Title>
              <Text variant="body-1">Almost done</Text>
            </Modal.Title>
            <Modal.Subtitle>
              Enter which font families you're going to use in Figma for the `{themeName}` theme
            </Modal.Subtitle>
          </View.Item>
          <FormControl>
            <FormControl.Label>Title font-family</FormControl.Label>
            <TextField
              name="titleFontFamily"
              placeholder={titleFontFallback}
              value={titleFontFamily}
              onChange={(args) => setTitleFontFamily(args.value)}
            />
            <FormControl.Helper>{theme?.fontFamily.title.family}</FormControl.Helper>
          </FormControl>
          <FormControl>
            <FormControl.Label>Body font-family</FormControl.Label>
            <TextField
              name="bodyFontFamily"
              placeholder={bodyFontFallback}
              value={bodyFontFamily}
              onChange={(args) => setBodyFontFamily(args.value)}
            />
            <FormControl.Helper>{theme?.fontFamily.body.family}</FormControl.Helper>
          </FormControl>
          <Divider />
          <Text variant="body-3" color="neutral-faded">
            Syncing the theme from the code will create new variables or override existing ones in the `{themeName}`{" "}
            variable mode.
          </Text>
          <View gap={2} direction="row">
            <Button color="primary" onClick={handleThemeUploadConfirm}>
              Continue
            </Button>
            <Button onClick={handleCancel}>Cancel</Button>
          </View>
        </View>
      </Modal>
    </>
  );
};

const container = document.getElementById("root")!;
const root = createRoot(container);
root.render(
  <Reshaped theme="figma">
    <App />
  </Reshaped>,
);
